import assert from 'node:assert/strict';
import fs from 'node:fs'; import os from 'node:os'; import path from 'node:path';
process.env.NO_LISTEN = '1'; process.env.DB = 'memory'; process.env.COOKIE_SECURE = '0';
process.env.DATA_DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'alif-')); process.env.OWNER_EMAIL = 'own@test.com';
const { server } = await import('../server.js');
await new Promise((r) => server.listen(0, r));
const base = `http://127.0.0.1:${server.address().port}`;
const mk = () => { const jar = {}; const h = () => ({ cookie: Object.entries(jar).map(([k, v]) => `${k}=${v}`).join('; ') });
  const call = async (method, p, body, extra = {}) => { const r = await fetch(base + p, { method, redirect: 'manual', headers: { ...h(), ...(typeof body === 'string' || !body ? {} : { 'content-type': 'application/x-www-form-urlencoded' }), ...extra }, body: body && typeof body === 'object' && !Buffer.isBuffer(body) ? new URLSearchParams(body).toString() : body });
    for (const c of r.headers.getSetCookie()) { const [kv] = c.split(';'); const i = kv.indexOf('='); jar[kv.slice(0, i)] = kv.slice(i + 1); }
    return { status: r.status, loc: r.headers.get('location'), buf: Buffer.from(await r.arrayBuffer()), ct: r.headers.get('content-type') }; };
  return { call, jar }; };
const jpg = Buffer.concat([Buffer.from([0xff, 0xd8, 0xff, 0xe0]), Buffer.alloc(200, 1)]);
const owner = mk(), guest = mk(), fam = mk();
await owner.call('GET', '/register'); 
let r = await owner.call('POST', '/register', { csrf: owner.jar.csrf, name: 'Own', email: 'own@test.com', password: 'longenough1', terms: '1' });
assert.equal(r.status, 303);
r = await guest.call('POST', '/alifbo/p/14', jpg, { 'x-alifbo': '1' }); assert.equal(r.status, 401);
r = await owner.call('POST', '/alifbo/p/14', jpg); assert.equal(r.status, 403);
r = await owner.call('POST', '/alifbo/p/14', Buffer.from('notanimage'), { 'x-alifbo': '1' }); assert.equal(r.status, 415);
r = await owner.call('POST', '/alifbo/p/14', jpg, { 'x-alifbo': '1' }); assert.equal(r.status, 200);
r = await owner.call('GET', '/alifbo/p/14'); assert.equal(r.status, 200); assert.equal(r.ct, 'image/jpeg');
r = await guest.call('GET', '/alifbo/p/14'); assert.equal(r.status, 404);
r = await guest.call('GET', '/alifbo/family'); assert.equal(r.status, 404);
r = await owner.call('GET', '/alifbo/family'); assert.equal(r.status, 200);
const code = r.buf.toString().match(/in\?c=([0-9a-f]+)/)[1];
r = await fam.call('GET', '/alifbo/in?c=bad'); assert.equal(r.status, 404);
r = await fam.call('GET', '/alifbo/in?c=' + code); assert.equal(r.status, 303);
r = await fam.call('GET', '/alifbo/p/14'); assert.equal(r.status, 200);
r = await fam.call('POST', '/alifbo/p/14', jpg, { 'x-alifbo': '1' }); assert.equal(r.status, 401);
r = await owner.call('GET', '/alifbo/p/999'); assert.equal(r.status, 404);
console.log('ALIFBO PAGES PASSED'); server.close(); process.exit(0);
