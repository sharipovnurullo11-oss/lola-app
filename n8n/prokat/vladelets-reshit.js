const B = $('Владелец: запрос').first().json.body || {};
const R = n => $(n).all().map(i => i.json).filter(r => r && r.id !== undefined);
const out = (resp, extra) => [{ json: Object.assign({ op: 'none', photos: [], resp: resp }, extra || {}) }];
const token = String(B.token || '');
const me = token.length >= 20 ? R('Владелец по ссылке').find(r => String(r.token) === token && r.aktivno !== false) : null;
if (!me) return out({ ok: false, error: 'ссылка не подходит' });
const point = String(me.tochka);
const norm = s => String(s || '').toLowerCase().replace(/\s+/g, ' ').trim();
const pk = s => norm(s).slice(0, 14);
const mine = r => pk(r.tochka) === pk(point);
const num = x => Math.round((Number(x) || 0) * 100) / 100;
const P = (h, d) => ({ min_chas: h, min_den: d });
const typeP = nm => { const s = norm(nm);
  if (/отбой|атбй|молот/.test(s)) return P(0, 100);
  if (/перф|парф/.test(s)) return /больш|калон|кадре|катта/.test(s) ? P(0, 70) : P(30, 40);
  if (/шруп|шур/.test(s)) return P(30, 40);
  if (/дрел/.test(s)) return P(0, 30);
  if (/болгар|балгар/.test(s)) return /больш|калон|кадре|катта/.test(s) ? P(30, 40) : P(20, 30);
  if (/утиг|утюг|утик|паяльн|турба/.test(s)) return P(20, 30);
  if (/вибрат/.test(s)) return P(0, 40);
  if (/лобзик|добзик/.test(s)) return P(0, 40);
  if (/бензопил/.test(s)) return P(0, 80);
  if (/циркул/.test(s)) return P(0, 40);
  if (/сварк/.test(s)) return P(0, 60);
  if (/краскопуль/.test(s)) return P(0, 70);
  if (/пушк/.test(s)) return P(0, 70);
  if (/горелк/.test(s)) return P(0, 50);
  if (/фен/.test(s)) return P(0, 40);
  if (/миксер/.test(s)) return P(0, 40);
  if (/резб|rodex|родекс/.test(s)) return P(0, 30);
  return P(0, 0); };
const prices = {};
R('Цены').forEach(r => { prices[norm(r.instrument)] = r; });
const tools = {};
const addTool = (nm, q, fid) => { const n = String(nm || '').replace(/\s+/g, ' ').trim(); if (!n || /масл|тряпк|баннер|банер|без названия|пылесос|насос|компрессор/.test(n.toLowerCase())) return; const k = norm(n); const t = tools[k] || (tools[k] = { name: n, qty: 0, out: 0, broken: 0, photo: '' }); t.qty += q; if (fid && !t.photo) t.photo = fid; };
const fromRec = {};
R('Записи инструментов').filter(r => String(r.tip) === 'Инструмент' && mine(r)).forEach(r => { const k = norm(r.instrument); fromRec[k] = 1; addTool(r.instrument, Math.max(1, Number(r.kolvo) || 1), ''); });
// Инструмент, который перевезли с этого пункта целиком, не возвращаем по старым фото.
R('Записи инструментов').filter(r => String(r.tip) === 'Перевезён' && mine(r)).forEach(r => { const k = norm(r.instrument); if (!fromRec[k]) fromRec[k] = 2; });
R('Фото по точкам').filter(r => mine(r) && r.drive_file_id).forEach(r => { const k = norm(r.instrument); if (fromRec[k]) { const t = tools[k]; if (t && !t.photo) t.photo = String(r.drive_file_id); } else addTool(r.instrument, 1, String(r.drive_file_id)); });
const allRows = R('Аренды').filter(r => String(r.tochka) === point);
const rentals = allRows.filter(r => r.status !== 'сдача');
const handRows = allRows.filter(r => r.status === 'сдача');
rentals.filter(r => r.status === 'в аренде').forEach(r => { const t = tools[norm(r.instrument)]; if (t) t.out += 1; });
rentals.filter(r => r.status === 'сломан').forEach(r => { const t = tools[norm(r.instrument)]; if (t) t.broken += 1; });
const list = Object.keys(tools).map(k => { const t = tools[k]; const p = prices[k] || typeP(t.name); return { name: t.name, qty: t.qty, out: t.out, broken: t.broken, free: Math.max(0, t.qty - t.out - t.broken), photo_id: t.photo, min_hour: num(p.min_chas), min_day: num(p.min_den) }; }).sort((a, b) => a.name.localeCompare(b.name));
const rl = rentals.slice().sort((a, b) => Number(b.id) - Number(a.id)).slice(0, 100).map(r => ({ id: String(r.oid), tool: String(r.instrument), start: String(r.nachalo), days: Number(r.dni) || 0, price_day: num(r.tsena_den), amount: num(r.summa), share: num(r.dolya_vladeltsa), status: String(r.status), returned: String(r.vozvrat || ''), deposit: String(r.zalog || ''), deposit_sum: num(r.zalog_summa), phone: String(r.telefon || ''), check: String(r.proverka || ''), repair_paid: num(r.remont_oplata) }));
const myTotal = num(rentals.reduce((s, r) => s + (Number(r.dolya_vladeltsa) || 0), 0));
const collected0 = num(rentals.reduce((s, r) => s + (Number(r.summa) || 0), 0));
const owedAll = num(rentals.reduce((s, r) => s + (Number(r.dolya_nurullo) || 0), 0));
const handed = num(handRows.reduce((s, r) => s + (Number(r.dolya_nurullo) || 0), 0));
const handovers = handRows.slice().sort((a, b) => Number(b.id) - Number(a.id)).slice(0, 50).map(r => ({ id: String(r.oid), date: String(r.nachalo), amount: num(r.dolya_nurullo) }));
const fin = (dc, dow) => ({ collected: num(collected0 + dc), owed: num(owedAll + dow - handed), handed: handed, handovers: handovers });
const base = () => Object.assign({ ok: true, point: { name: point, owner: String(me.vladelets || '') }, tools: list, rentals: rl, earned: myTotal }, fin(0, 0));
const act = String(B.action || 'me');
if (act === 'me') return out(base());
const date = new Date(Date.now() + 5 * 3600 * 1000).toISOString().slice(0, 10);
const okImg = s => typeof s === 'string' && /^data:image\/jpeg;base64,[A-Za-z0-9+\/=]+$/.test(s) && s.length > 200 && s.length < 2000000;
const b64 = s => s.slice(s.indexOf(',') + 1);
const bp = () => ({ name: point, owner: String(me.vladelets || '') });
if (act === 'rent') {
  const tool = String(B.tool || '');
  const t = list.find(x => x.name === tool);
  const days = Math.round(Number(B.days)), price = num(B.price);
  const id = String(B.id || '').replace(/[^a-zA-Z0-9]/g, '').slice(0, 40);
  const zalog = String(B.zalog || ''), zsum = num(B.zalog_sum);
  const phone = String(B.phone || '').replace(/[^0-9+]/g, '').slice(0, 16);
  if (!t) return out({ ok: false, error: 'такого инструмента на пункте нет' });
  if (!(days >= 1 && days <= 365)) return out({ ok: false, error: 'дни: от 1 до 365' });
  if (!(price > 0 && price <= 100000)) return out({ ok: false, error: 'неверная цена за день' });
  if (t.min_day > 0 && price < t.min_day) return out({ ok: false, error: 'цена ниже минимальной: ' + t.min_day + ' сомони в день' });
  if (id.length < 6) return out({ ok: false, error: 'нет номера записи' });
  if (allRows.some(r => String(r.oid) === id)) return out(base());
  if (t.free < 1) return out({ ok: false, error: 'этот инструмент уже в аренде или сломан' });
  if (zalog !== 'паспорт' && zalog !== 'деньги') return out({ ok: false, error: 'выберите залог: паспорт или деньги' });
  if (zalog === 'деньги' && !(zsum > 0 && zsum <= 1000000)) return out({ ok: false, error: 'укажите сумму залога' });
  if (phone.replace(/\D/g, '').length < 7) return out({ ok: false, error: 'укажите телефон арендатора' });
  if (B.consent !== true) return out({ ok: false, error: 'нужно согласие арендатора на фото' });
  if (!okImg(B.photo_person)) return out({ ok: false, error: 'нужно фото арендатора' });
  if (zalog === 'паспорт' && !okImg(B.photo_passport)) return out({ ok: false, error: 'нужно фото паспорта' });
  const amount = num(price * days);
  const share = Math.round(amount * 0.2 * 100) / 100;
  const row = { oid: id, tochka: point, instrument: t.name, nachalo: date, dni: days, summa: amount, dolya_vladeltsa: share, dolya_nurullo: num(amount - share), status: 'в аренде', vozvrat: '', avtor: 'владелец', tsena_den: price, zalog: zalog, zalog_summa: zalog === 'деньги' ? zsum : 0, telefon: phone, foto_cheloveka: '', foto_pasporta: '', proverka: '', foto_vozvrata: '', remont_oplata: 0 };
  const photos = [{ field: 'foto_cheloveka', name: 'chel_' + id + '.jpg', b64: b64(B.photo_person) }];
  if (zalog === 'паспорт') photos.push({ field: 'foto_pasporta', name: 'pasport_' + id + '.jpg', b64: b64(B.photo_passport) });
  const nowRl = [{ id: id, tool: t.name, start: date, days: days, price_day: price, amount: amount, share: share, status: 'в аренде', returned: '', deposit: zalog, deposit_sum: row.zalog_summa, phone: phone, check: '', repair_paid: 0 }].concat(rl);
  const nl = list.map(x => x.name === t.name ? Object.assign({}, x, { out: x.out + 1, free: x.free - 1 }) : x);
  return out(Object.assign({ ok: true, point: bp(), tools: nl, rentals: nowRl, earned: num(myTotal + share) }, fin(amount, row.dolya_nurullo)), { op: 'rent', row: row, photos: photos });
}
if (act === 'return') {
  const id = String(B.id || '').replace(/[^a-zA-Z0-9]/g, '').slice(0, 40);
  const r = rentals.find(x => String(x.oid) === id);
  if (!r) return out({ ok: false, error: 'аренда не найдена' });
  if (r.status !== 'в аренде') return out(base());
  const check = String(B.check || '');
  if (check !== 'работает' && check !== 'поврежден') return out({ ok: false, error: 'включите инструмент и отметьте: работает или повреждён' });
  if (!okImg(B.photo)) return out({ ok: false, error: 'нужно фото инструмента при возврате' });
  const repair = check === 'поврежден' ? num(B.repair_pay) : 0;
  if (check === 'поврежден' && !(repair >= 0 && repair <= 1000000)) return out({ ok: false, error: 'неверная сумма за ремонт' });
  const nl = list.map(x => x.name === String(r.instrument) ? Object.assign({}, x, { out: Math.max(0, x.out - 1), free: x.free + 1 }) : x);
  const nowRl = rl.map(x => x.id === id ? Object.assign({}, x, { status: 'вернули', returned: date, check: check, repair_paid: repair }) : x);
  return out(Object.assign({ ok: true, point: bp(), tools: nl, rentals: nowRl, earned: myTotal }, fin(0, 0)), { op: 'return', oid: id, date: date, upd: { status: 'вернули', vozvrat: date, proverka: check, remont_oplata: repair, foto_vozvrata: '' }, photos: [{ field: 'foto_vozvrata', name: 'vozvrat_' + id + '.jpg', b64: b64(B.photo) }] });
}
if (act === 'broken') {
  const t = list.find(x => x.name === String(B.tool || ''));
  const id = String(B.id || '').replace(/[^a-zA-Z0-9]/g, '').slice(0, 40);
  if (!t) return out({ ok: false, error: 'такого инструмента на пункте нет' });
  if (id.length < 6) return out({ ok: false, error: 'нет номера записи' });
  if (allRows.some(r => String(r.oid) === id)) return out(base());
  if (t.free < 1) return out({ ok: false, error: 'сначала верните инструмент из аренды' });
  const row = { oid: id, tochka: point, instrument: t.name, nachalo: date, dni: 0, summa: 0, dolya_vladeltsa: 0, dolya_nurullo: 0, status: 'сломан', vozvrat: '', avtor: 'владелец', tsena_den: 0, zalog: '', zalog_summa: 0, telefon: '', foto_cheloveka: '', foto_pasporta: '', proverka: '', foto_vozvrata: '', remont_oplata: 0 };
  const nowRl = [{ id: id, tool: t.name, start: date, days: 0, price_day: 0, amount: 0, share: 0, status: 'сломан', returned: '', deposit: '', deposit_sum: 0, phone: '', check: '', repair_paid: 0 }].concat(rl);
  const nl = list.map(x => x.name === t.name ? Object.assign({}, x, { broken: x.broken + 1, free: x.free - 1 }) : x);
  return out(Object.assign({ ok: true, point: bp(), tools: nl, rentals: nowRl, earned: myTotal }, fin(0, 0)), { op: 'rent', row: row });
}
if (act === 'fixed') {
  const id = String(B.id || '').replace(/[^a-zA-Z0-9]/g, '').slice(0, 40);
  const r = rentals.find(x => String(x.oid) === id);
  if (!r) return out({ ok: false, error: 'запись не найдена' });
  if (r.status !== 'сломан') return out(base());
  const nl = list.map(x => x.name === String(r.instrument) ? Object.assign({}, x, { broken: Math.max(0, x.broken - 1), free: x.free + 1 }) : x);
  const nowRl = rl.map(x => x.id === id ? Object.assign({}, x, { status: 'вернули', returned: date, check: 'починен' }) : x);
  return out(Object.assign({ ok: true, point: bp(), tools: nl, rentals: nowRl, earned: myTotal }, fin(0, 0)), { op: 'return', oid: id, date: date, upd: { status: 'вернули', vozvrat: date, proverka: 'починен', remont_oplata: 0, foto_vozvrata: '' } });
}
if (act === 'handover') {
  const id = String(B.id || '').replace(/[^a-zA-Z0-9]/g, '').slice(0, 40);
  if (id.length < 6) return out({ ok: false, error: 'нет номера записи' });
  if (allRows.some(r => String(r.oid) === id)) return out(base());
  const f = fin(0, 0);
  if (!(f.owed > 0)) return out({ ok: false, error: 'передавать нечего' });
  if (num(B.amount) !== f.owed) return out({ ok: false, error: 'сумма изменилась, обновите экран: к передаче ' + f.owed });
  const row = { oid: id, tochka: point, instrument: 'Сдача денег', nachalo: date, dni: 0, summa: 0, dolya_vladeltsa: 0, dolya_nurullo: f.owed, status: 'сдача', vozvrat: '', avtor: 'владелец', tsena_den: 0, zalog: '', zalog_summa: 0, telefon: '', foto_cheloveka: '', foto_pasporta: '', proverka: '', foto_vozvrata: '', remont_oplata: 0 };
  const hv = [{ id: id, date: date, amount: f.owed }].concat(handovers);
  return out(Object.assign({ ok: true, point: bp(), tools: list, rentals: rl, earned: myTotal }, { collected: f.collected, owed: 0, handed: num(f.handed + f.owed), handovers: hv }), { op: 'rent', row: row });
}
return out({ ok: false, error: 'неизвестное действие' });
